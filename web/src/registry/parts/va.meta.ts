const link = "{ label: string; href: string } | null";

function scrollProps(accent: string, duration: number, length: number): EffectProp[] {
  return [
    { name: "accent", type: "string", default: `"${accent}"`, description: "Accent color used for highlights, buttons and progress details." },
    { name: "progress", type: "number", default: "undefined", description: "Controlled progress from 0 to 1. When set, scroll tracking and autoplay are ignored." },
    { name: "autoPlay", type: "boolean", default: "false", description: "Loops the progress by itself, forward, hold, then back. Use it for previews where nobody scrolls." },
    { name: "duration", type: "number", default: String(duration), description: "Seconds for one forward pass of the autoplay loop." },
    { name: "length", type: "number", default: String(length), description: "Scroll distance in stage heights while the hero is pinned. Ignored with progress or autoPlay." },
    { name: "height", type: "string", default: '"100vh"', description: "Height of the pinned stage. Use a pixel value when the hero lives inside a scrolling container." },
    { name: "headingAs", type: '"h1" | "h2"', default: '"h1"', description: "Heading level of the headline. Use h2 when the page already has an h1." },
  ];
}

